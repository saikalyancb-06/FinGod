"""Train and evaluate the account-level money-mule classifier.

Train scenario: synthetic seed 1. Held-out scenario: synthetic seed 2 (different
accounts, rings and timings - entity-aware separation). Baselines: rules-only
and logistic regression. Writes ml/artifacts/mule_model.joblib, metrics JSON
and docs/MULE_MODEL_CARD.md.

  python -m ml.train_mule_model
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, precision_recall_curve, roc_auc_score
from sklearn.model_selection import GroupKFold, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from xgboost import XGBClassifier

from ml.generate_mule_data import generate
from mule.features import FEATURE_COLUMNS, compute_features, normalize_transactions
from shared.config import ARTIFACT_DIR, ROOT

GEN_DIR = ROOT / "data" / "generated"
SAMPLES = ROOT / "data" / "samples"


def build(seed: int, accounts: int, rings: int, save_prefix: Path | None = None):
    tx, lab = generate(seed, accounts, rings)
    if save_prefix:
        save_prefix.parent.mkdir(parents=True, exist_ok=True)
        tx.to_csv(f"{save_prefix}_transactions.csv", index=False)
        lab.to_csv(f"{save_prefix}_labels.csv", index=False)
    df, _ = normalize_transactions(tx)
    res = compute_features(df)
    feats = res.features.join(lab.set_index("account"), how="left")
    feats["is_mule"] = feats["is_mule"].fillna(0).astype(int)
    feats["rules_hit"] = [len(res.evidence[a]["rules"]) for a in feats.index]
    feats["ring_id"] = feats["ring_id"].fillna("")
    return feats


def metrics_at(y, score, thr):
    pred = score >= thr
    tp = int(((pred == 1) & (y == 1)).sum()); fp = int(((pred == 1) & (y == 0)).sum())
    fn = int(((pred == 0) & (y == 1)).sum()); tn = int(((pred == 0) & (y == 0)).sum())
    return {
        "precision": round(tp / (tp + fp), 4) if tp + fp else 0.0,
        "recall": round(tp / (tp + fn), 4) if tp + fn else 0.0,
        "false_positive_rate": round(fp / (fp + tn), 5) if fp + tn else 0.0,
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
    }


def main():
    t0 = time.time()
    print("Generating SYNTHETIC train scenario (seed 1)…")
    train = build(1, 1200, 8, GEN_DIR / "mule_train")
    print("Generating SYNTHETIC held-out scenario (seed 2)…")
    test = build(2, 900, 6, GEN_DIR / "mule_heldout")
    print("Generating SYNTHETIC demo upload file (seed 3)…")
    tx_demo, lab_demo = generate(3, 350, 2)
    SAMPLES.mkdir(parents=True, exist_ok=True)
    tx_demo.to_csv(SAMPLES / "mule_demo_transactions.csv", index=False)
    lab_demo.to_csv(SAMPLES / "mule_demo_labels_for_evaluation.csv", index=False)

    X, y = train[FEATURE_COLUMNS].values, train["is_mule"].values
    Xt, yt = test[FEATURE_COLUMNS].values, test["is_mule"].values
    groups = np.where(train["ring_id"] != "", train["ring_id"], train.index.to_numpy())

    pos_w = float((y == 0).sum() / max(1, (y == 1).sum()))
    xgb = XGBClassifier(
        n_estimators=300, max_depth=4, learning_rate=0.05, subsample=0.9, colsample_bytree=0.9,
        scale_pos_weight=pos_w, eval_metric="aucpr", random_state=42, n_jobs=4,
    )
    # threshold chosen on out-of-fold predictions of the TRAIN scenario (ring-aware folds)
    oof = cross_val_predict(xgb, X, y, cv=GroupKFold(n_splits=5), groups=groups, method="predict_proba")[:, 1]
    p, r, th = precision_recall_curve(y, oof)
    f1 = 2 * p * r / np.clip(p + r, 1e-9, None)
    thr = float(th[int(np.argmax(f1[:-1]))])
    xgb.fit(X, y)
    s_xgb = xgb.predict_proba(Xt)[:, 1]

    lr = make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000, class_weight="balanced"))
    lr.fit(X, y)
    s_lr = lr.predict_proba(Xt)[:, 1]
    s_rules = test["rules_hit"].values.astype(float)

    def block(name, s, thr_):
        return {"model": name, "roc_auc": round(roc_auc_score(yt, s), 4), "pr_auc": round(average_precision_score(yt, s), 4),
                "at_threshold": metrics_at(yt, s, thr_), "threshold": thr_}

    results = {
        "data": "SYNTHETIC (generated by ml/generate_mule_data.py). Not evidence of real-world performance.",
        "train_scenario": {"accounts": int(len(train)), "mules": int(y.sum())},
        "heldout_scenario": {"accounts": int(len(test)), "mules": int(yt.sum())},
        "chosen_threshold": round(thr, 4),
        "xgboost": block("XGBoost", s_xgb, thr),
        "baseline_logistic_regression": block("LogReg", s_lr, 0.5),
        "baseline_rules_only(>=1 rule)": block("Rules", s_rules, 1.0),
        "baseline_rules_only(>=2 rules)": block("Rules2", s_rules, 2.0),
        "recall_by_typology": {},
        "false_positives_by_type": {},
    }
    test = test.assign(score=s_xgb, flagged=s_xgb >= thr)
    for typ, g in test[test.is_mule == 1].groupby("typology"):
        results["recall_by_typology"][typ] = round(float(g["flagged"].mean()), 3)
    fps = test[(test.is_mule == 0) & test.flagged]
    results["false_positives_by_type"] = fps["typology"].value_counts().to_dict()
    imp = sorted(zip(FEATURE_COLUMNS, xgb.feature_importances_.tolist()), key=lambda x: -x[1])
    results["feature_importance"] = [(k, round(v, 4)) for k, v in imp]
    results["trained_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
    results["model_version"] = f"mule-xgb-{time.strftime('%Y%m%d%H%M')}"

    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump({"model": xgb, "features": FEATURE_COLUMNS, "threshold": thr, "version": results["model_version"], "feature_set": "legacy_v0"},
                ARTIFACT_DIR / "mule_model_synthetic.joblib")
    (ARTIFACT_DIR / "mule_metrics_synthetic.json").write_text(json.dumps(results, indent=2))
    write_card(results)
    print(json.dumps({k: results[k] for k in ["xgboost", "baseline_rules_only(>=1 rule)", "recall_by_typology", "false_positives_by_type"]}, indent=2))
    print(f"done in {time.time()-t0:.1f}s")


def write_card(m: dict):
    x = m["xgboost"]
    rows = "\n".join(
        f"| {k} | {v['roc_auc']} | {v['pr_auc']} | {v['at_threshold']['precision']} | {v['at_threshold']['recall']} | {v['at_threshold']['false_positive_rate']} |"
        for k, v in [("XGBoost (chosen thr)", m["xgboost"]), ("Logistic regression (0.5)", m["baseline_logistic_regression"]),
                     ("Rules only, ≥1 rule", m["baseline_rules_only(>=1 rule)"]), ("Rules only, ≥2 rules", m["baseline_rules_only(>=2 rules)"])]
    )
    card = f"""# Money Mule Classifier — Model Card

**Version:** {m['model_version']} · trained {m['trained_at']}

## What it is
An account-level XGBoost classifier over engineered transaction, temporal and graph
features (`mule/features.py`). It is **one of three evidence layers** (rules, ML,
graph analytics). Its score is never averaged with rule counts; alerts are
prioritised by explicit rules (see `mule/detection.py`).

## Data — SYNTHETIC
{m['data']}

* Train scenario: {m['train_scenario']['accounts']} accounts, {m['train_scenario']['mules']} injected mule accounts.
* Held-out scenario (different seed, different accounts/rings): {m['heldout_scenario']['accounts']} accounts, {m['heldout_scenario']['mules']} mules.
* Injected typologies: fan-in/fan-out, rapid pass-through chains, temporal cycles, amount splitting (45k–50k), dormant activation.
* Background includes legitimate merchants (high fan-in) and legitimately re-activated accounts so false positives are measurable.

## Validation
* Decision threshold ({m['chosen_threshold']}) chosen from ring-aware GroupKFold out-of-fold predictions on the train scenario only.
* Metrics below are on the held-out scenario. Accuracy is not reported (heavily imbalanced).

| Model | ROC-AUC | PR-AUC | Precision | Recall | FPR |
|---|---|---|---|---|---|
{rows}

Recall by typology (XGBoost): `{json.dumps(m['recall_by_typology'])}`

False positives by true account type: `{json.dumps(m['false_positives_by_type'])}`

## Limitations
* Synthetic data with generator-known patterns: results are optimistic and **do not
  establish real-world performance**.
* Thresholds must be re-validated on authorised institutional data before use.
* An alert is a reason for human review, not proof of wrongdoing. The system never
  freezes accounts or labels people as criminals.
* AML scores must not flow into any credit decision (enforced by architecture: separate service, store and auth).
"""
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "MULE_MODEL_CARD_SYNTHETIC.md").write_text(card, encoding="utf-8")


if __name__ == "__main__":
    main()
